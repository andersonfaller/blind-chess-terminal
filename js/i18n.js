// Interface strings in English and Brazilian Portuguese.
// t('key', { var }) interpolates {var}; missing Portuguese falls back to English.

let lang = 'en';

export function setLang(l) {
  lang = l === 'pt' ? 'pt' : 'en';
}

export function getLang() {
  return lang;
}

export function t(key, vars) {
  const entry = S[key];
  let s = entry ? (entry[lang] ?? entry.en) : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}

export function hasKey(key) {
  return key in S;
}

